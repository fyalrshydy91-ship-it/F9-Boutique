-- Only the catalog is connected. No accounts, orders, or checkout tables.
create table public.boutiques (
  id integer generated by default as identity primary key,
  name text not null check (length(name) > 0),
  ar text not null check (length(ar) > 0),
  mark text not null,
  line text not null,
  "lineAr" text not null,
  story text not null,
  "storyAr" text not null
);

create table public.products (
  id integer generated by default as identity primary key,
  name text not null check (length(name) > 0),
  ar text not null check (length(ar) > 0),
  brand integer not null references public.boutiques(id) on delete restrict,
  price numeric(12,3) not null check (price >= 0),
  image text not null check (image ~ '^[a-z0-9-]+$'),
  category text not null check (category in ('abayas', 'women')),
  sizes text[] not null check (cardinality(sizes) > 0),
  colors jsonb not null check (jsonb_typeof(colors) = 'array' and jsonb_array_length(colors) > 0),
  description text not null,
  "descriptionAr" text not null,
  fresh boolean not null default false,
  best boolean not null default false
);
create index products_brand_idx on public.products(brand);

alter table public.boutiques enable row level security;
alter table public.products enable row level security;
revoke all on table public.boutiques, public.products from anon, authenticated;
grant select on table public.boutiques, public.products to anon, authenticated;
revoke all on sequence public.boutiques_id_seq, public.products_id_seq from anon, authenticated;
create policy "Public catalog boutiques are readable"
  on public.boutiques for select to anon, authenticated using (true);
create policy "Public catalog products are readable"
  on public.products for select to anon, authenticated using (true);
